# SUM AND DIFFERENCE

num1 = int(input("Enter first number:"))
num2 = int(input("Enter second number:"))

def calculate_sum():
    sum = num1 + num2
    print("Sum:", sum)

def calculate_difference():
    difference = num1 - num2
    print("Difference:", difference)

calculate_sum()
calculate_difference()

